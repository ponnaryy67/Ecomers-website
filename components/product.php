    function setTrackPosition(track, index) {
        track.style.transform =
            `translateX(-${index * (100 / 4 + 0.5)}%)`;
    }

    function moveSlider(sectionId, direction, totalOriginal) {
        const track = document.getElementById(`slider-track-${sectionId}`);

        let currentIndex =
            parseInt(track.getAttribute('data-index'));

        currentIndex += direction;

        track.setAttribute('data-index', currentIndex);
        track.classList.add('transition-ease');

        setTrackPosition(track, currentIndex);
    }

    document.addEventListener("DOMContentLoaded", () => {

        const tracks =
            document.querySelectorAll('.slider-track');

        tracks.forEach(track => {

            const totalOriginal =
                parseInt(track.getAttribute('data-total'));

            setTrackPosition(track, totalOriginal);

            track.addEventListener('transitionend', () => {

                let currentIndex =
                    parseInt(track.getAttribute('data-index'));

                if (currentIndex >= totalOriginal * 2) {

                    track.classList.remove('transition-ease');

                    currentIndex -= totalOriginal;

                    track.setAttribute(
                        'data-index',
                        currentIndex
                    );

                    setTrackPosition(
                        track,
                        currentIndex
                    );

                } else if (currentIndex < totalOriginal) {

                    track.classList.remove('transition-ease');

                    currentIndex += totalOriginal;

                    track.setAttribute(
                        'data-index',
                        currentIndex
                    );

                    setTrackPosition(
                        track,
                        currentIndex
                    );
                }
            });
        });

    });

    async function toggleWishlist(buttonElement, product) {
    if (!product || product.id == null || product.id === '') {
        console.error('Product ID is missing.');
        return;
    }

    const isActive = buttonElement.classList.contains('active');

    const formData = new FormData();
    formData.append('action', isActive ? 'remove' : 'add');
    formData.append('id', String(product.id));
    formData.append('name', product.title ?? '');
    formData.append('price', String(product.price ?? 0));
    formData.append('image', product.image ?? '');

    try {
        const response = await fetch('add-to-wishlist.php', {
            method: 'POST',
            body: formData
        });

        const data = await response.json();

        if (!response.ok || !data.success) {
            throw new Error(data.message || 'Wishlist update failed');
        }

        buttonElement.classList.toggle('active', data.action === 'add');

        const badge = document.getElementById('wishlistCountBadge');
        if (badge) {
            const count = Number(data.wishlistCount) || 0;
            badge.textContent = count;
            badge.style.display = count > 0 ? 'flex' : 'none';
        }

    } catch (error) {
        console.error('Wishlist error:', error);
        alert('មានបញ្ហាក្នុងការបន្ថែម Favorite។ សូមពិនិត្យ add-to-wishlist.php។');
    }
}

    function openProductModal(product) {

        currentModalProduct = product;
        currentModalQty = 1;

        document.getElementById('modalImg').src =
            product.image;

        document.getElementById('modalImg').alt =
            product.title;

        document.getElementById('modalTitle').innerText =
            product.title;

        document.getElementById('modalQty').innerText =
            currentModalQty;

        updateModalPriceDisplay();

        document
            .getElementById('productModal')
            .classList.add('active');

        document.body.style.overflow = 'hidden';
    }

    function closeProductModal() {

        document
            .getElementById('productModal')
            .classList.remove('active');

        document.body.style.overflow = 'auto';
    }

    function updateModalQty(change) {

        currentModalQty =
            Math.max(1, currentModalQty + change);

        document.getElementById('modalQty').innerText =
            currentModalQty;

        updateModalPriceDisplay();
    }

    function updateModalPriceDisplay() {

        if (currentModalProduct) {

            const totalPrice =
                currentModalProduct.price *
                currentModalQty;

            document.getElementById('modalPrice').innerText =
                `US $${totalPrice.toFixed(2)}`;
        }
    }

