    function handleModalAddToCart() {

        if (!currentModalProduct) {
            return;
        }

        const formData = new FormData();

        formData.append(
            'action',
            'add_to_cart'
        );

        formData.append(
            'id',
            currentModalProduct.id
        );

        formData.append(
            'name',
            currentModalProduct.title
        );

        formData.append(
            'price',
            currentModalProduct.price
        );

        formData.append(
            'image',
            currentModalProduct.image
        );

        formData.append(
            'quantity',
            currentModalQty
        );

        // Product page does not have size/color
        formData.append(
            'size',
            ''
        );

        formData.append(
            'color',
            ''
        );


        fetch('add-to-cart.php', {

            method: 'POST',

            headers: {
                'X-Requested-With': 'XMLHttpRequest'
            },

            body: formData

        })

        .then(response => {

            if (!response.ok) {
                throw new Error(
                    'Server error: ' + response.status
                );
            }

            return response.json();

        })

        .then(data => {

            console.log('Cart response:', data);

            if (!data.success) {

                throw new Error(
                    'Product was not added to cart'
                );
            }


            // Update cart badge
            const cartBadge =
                document.querySelector('.cart-badge');

            if (cartBadge) {

                cartBadge.innerText =
                    data.cartCount;

                cartBadge.style.display =
                    'flex';
            }


            const productName =
                currentModalProduct.title;

            const quantity =
                currentModalQty;


            closeProductModal();


            alert(
                productName +
                '\nQuantity: ' +
                quantity +
                '\n\nបានបន្ថែមទៅក្នុង Cart!'
            );


            // Reload so Header gets the latest session cart
            window.location.reload();

        })

        .catch(error => {

            console.error(
                'Add to cart error:',
                error
            );

            alert(
                'មានបញ្ហាក្នុងការបន្ថែម Product ទៅ Cart។\n' +
                'សូមព្យាយាមម្ដងទៀត។'
            );
        });
    }


